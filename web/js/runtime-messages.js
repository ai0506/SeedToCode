window.runtimeMessage = function runtimeMessage(error) {
   const template = window.RUNTIME_MESSAGES[error.messageKey] || error.messageKey || '未知运行时错误';
   return template.replace(/\{([A-Za-z0-9_]+)\}/g, function (_, key) {
      return error.args && error.args[key] !== undefined ? String(error.args[key]) : key;
   });
}
