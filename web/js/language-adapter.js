  function interpolate(template, args) {
    return template.replace(/\{([A-Za-z0-9_]+)\}/g, function (_, key) {
      return args && args[key] !== undefined ? String(args[key]) : key;
    });
  }

  function adapt(diagnostic) {
    const range = diagnostic.range;
    const template = MESSAGES[diagnostic.messageKey] || ('检测到问题：' + diagnostic.messageKey);
    const adapted = {
      code: diagnostic.code,
      ruleId: diagnostic.ruleId,
      line: range.start.line,
      col: range.start.column,
      endLine: range.end.line,
      endCol: range.end.column,
      startOffset: range.start.offset,
      endOffset: range.end.offset,
      severity: diagnostic.severity,
      origin: diagnostic.origin,
      message: interpolate(template, diagnostic.args),
      related: diagnostic.related || []
    };
    if (diagnostic.fix) {
      adapted.fix = {
        type: 'replaceRange',
        line: diagnostic.fix.range.start.line,
        col: diagnostic.fix.range.start.column,
        length: diagnostic.fix.range.end.offset - diagnostic.fix.range.start.offset,
        startOffset: diagnostic.fix.range.start.offset,
        endOffset: diagnostic.fix.range.end.offset,
        text: diagnostic.fix.newText
      };
    }
    return adapted;
  }

  function diagnose(source) {
    return engine.analyzeSource(source).diagnostics.map(adapt);
  }

  function formatSource(source, options) {
    return engine.format(source, options || {});
  }

  return { diagnose: diagnose, adaptOne: adapt, format: formatSource, raw: engine };
