#!/usr/bin/env node
// 从网页那一份源文件导出原生实验室要用的数据，写成一份 JSON：
//   - web/js/caie-spec.js：关键字、类型、内置函数、结构模板、缩进
//   - web/js/samples.js：出厂样例（编辑器验收和性能量具都用它，不手抄）
//   - web/css/styles.css：浅色 / 深色两套配色变量
//
// 为什么导出而不是在 Swift 里写一份：两份关键字表、两份配色迟早分叉，
// 而 App 那一份没人在浏览器里天天看。打包时现导，来源永远是网页那一份。
//
// 用法：node native/macos/scripts/export-web-spec.mjs <输出文件>
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const out = process.argv[2];
if (!out) {
  console.error("用法：export-web-spec.mjs <输出文件>");
  process.exit(1);
}

// 两个文件都是写 window.XXX 的 IIFE，给一个只有 window 的沙箱就能跑。
const sandbox = { window: {} };
vm.createContext(sandbox);
for (const file of ["web/js/caie-spec.js", "web/js/samples.js"]) {
  vm.runInContext(readFileSync(join(root, file), "utf8"), sandbox, { filename: file });
}
const CAIE = sandbox.window.CAIE;
const SAMPLES = sandbox.window.SAMPLES;
if (!CAIE || !SAMPLES) throw new Error("caie-spec.js 或 samples.js 没有定义预期的全局对象");

// 只认两块：:root { … } 和 html[data-theme="dark"] { … }
const css = readFileSync(join(root, "web/css/styles.css"), "utf8");
function block(selector) {
  const start = css.indexOf(selector + " {");
  if (start < 0) throw new Error("styles.css 里找不到 " + selector);
  const body = css.slice(css.indexOf("{", start) + 1, css.indexOf("}", start));
  const vars = {};
  for (const match of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) vars[match[1]] = match[2].trim();
  return vars;
}

const spec = {
  source: "generated by native/macos/scripts/export-web-spec.mjs — do not edit",
  version: CAIE.version,
  indent: CAIE.INDENT,
  keywords: CAIE.KEYWORDS,
  types: CAIE.TYPES,
  builtins: CAIE.BUILTINS.map((b) => ({ name: b.name, signature: b.sig, description: b.desc })),
  snippets: CAIE.SNIPPETS.map((s) => ({ label: s.label, body: s.body })),
  samples: {
    docs: SAMPLES.docs.map((d) => ({ id: d.id, name: d.name, source: d.source })),
    runtimeFiles: SAMPLES.runtimeFiles
  },
  theme: { light: block(":root"), dark: block('html[data-theme="dark"]') }
};

writeFileSync(out, JSON.stringify(spec, null, 2));
